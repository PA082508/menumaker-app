-- ============================================================================
-- 20260729c — dispatch_routes: сперва арендатор, потом сужение.
-- Применено 29.07, четвёртой и последней в утренней партии.
--
-- ПОЧЕМУ ЭТО ДВЕ ПОЛОВИНЫ, А НЕ ОДНА. Утренний замер отменил простое сужение:
-- на таблице стояли dr_read (USING true, чтение всем вошедшим) и dr_manage
-- (`org_id is not null and core.is_org_member(org_id)`, запись). Все ВОСЕМЬ
-- строк несут org_id = NULL — то есть снятие dr_read спрятало бы все восемь
-- маршрутов от всех, включая владельца, и заодно объяснило бы, почему их
-- нельзя было править: dr_manage на них и так никогда не срабатывала.
--
-- Иначе говоря, найденное — не «открытое чтение», а СТРОКИ БЕЗ АРЕНДАТОРА, у
-- которых открытое чтение было единственным способом остаться видимыми.
--
-- ЧТО ЗАПОЛНЯЕМ И НА КАКОМ ОСНОВАНИИ. В базе РОВНО ОДНА организация —
-- «Play Academy» (замер 29.07: core.organizations = 1, у всех центров тот же
-- org_id). Принадлежность не выводится и не угадывается: другой организации,
-- которой эти маршруты могли бы принадлежать, не существует. Это единственный
-- случай, когда бэкфилл арендатора не требует разбора построчно.
--
-- ЧТО ЭТО ЗА СТРОКИ. Восемь правил доставки: скан лицензии → офис, скан
-- документа → офис, скан утверждения → директор, скан на право питания →
-- директор (с формой ieg_application), скан замены → директор
-- (special_diet_statement), прогон импорта детей → офис. Персональных данных
-- нет; ценность — в том, что без них ничего никуда не доставляется.
--
-- ФОРМУЛА ПОСЛЕ БЭКФИЛЛА: свой в организации, оба источника ролей
-- (menumaker.in_org, см. 20260729a — у бухгалтера нет строки в
-- core.memberships, и одна core.is_org_member ослепила бы его молча).
--
-- NOT NULL ставится следом: строка без арендатора теперь не «видна всем»,
-- а невидима никому — значит её нельзя позволить создать.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- ЧТО НАШЁЛ READ-BACK, И ПОЧЕМУ ЭТО НЕ РЕГРЕСС. Вторая половина ворот («а
-- пропускают ли они нужное?») дала отказ у ВСЕХ девяти логинов: правит 0 строк,
-- «permission denied for table dispatch_routes». Замер грантов объяснил без
-- догадок: у роли authenticated на этой таблице ГРАНТ ТОЛЬКО SELECT — ни
-- INSERT, ни UPDATE, ни DELETE, и так было ДО миграции.
--
-- Значит снятая dr_manage (`is_org_member(org_id)`) была декоративной дважды:
-- её предикат не срабатывал никогда (org_id = NULL) и права под ней всё равно
-- не было. Маршрутами распоряжается service_role, не приложение.
--
-- Прав НЕ ДОБАВЛЯЕМ: расширять доступ без слова — не наша работа, а «раз ворота
-- закрыты, откроем» есть ровно та ошибка, против которой стоит вторая половина
-- проверки. Записано как есть: таблица приложению доступна на чтение.
-- ─────────────────────────────────────────────────────────────────────────────
-- ============================================================================

-- ── половина 1: арендатор ───────────────────────────────────────────────────
update menumaker.dispatch_routes
   set org_id = (select id from core.organizations limit 1)
 where org_id is null;

alter table menumaker.dispatch_routes
  alter column org_id set not null;

-- ── половина 2: сужение ─────────────────────────────────────────────────────
drop policy if exists dr_read   on menumaker.dispatch_routes;
drop policy if exists dr_manage on menumaker.dispatch_routes;

create policy dr_scope on menumaker.dispatch_routes
  for all to authenticated
  using      (menumaker.in_org(org_id))
  with check (menumaker.in_org(org_id));

comment on table menumaker.dispatch_routes is
  'Область: свой в организации (20260729c). До этого чтение было открыто всем '
  'вошедшим — и это было единственное, что делало строки видимыми: все восемь '
  'несли org_id = NULL, при котором политика записи не срабатывала никогда.';
