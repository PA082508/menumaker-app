import { describe, it, expect } from 'vitest'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
// @ts-expect-error — детектор один на карту и на гард, он .mjs без типов
import { scanCyrillicUi, stripComments } from '../../scripts/uiLanguageScan.mjs'

// ============================================================================
// ГАРД ЯЗЫКА ИНТЕРФЕЙСА — сборка падает на кириллице в UI.
//
// ПРАВИЛО ВЛАДЕЛЬЦА (закреплено, подтверждено 04.08): весь UI — только
// английский; русский живёт в комментариях кода.
//
// ПОЧЕМУ ГАРД, А НЕ ДИСЦИПЛИНА. Экран счёта писался по-русски для кухни, и
// каждый следующий заход дописывал рядом ещё строку — по-русски, потому что
// вокруг было по-русски. Так язык интерфейса разъезжается не решением, а
// соседством. Правило, которое держится на памяти, держится до первого
// торопливого вечера; это же правило в сборке не забывается никогда.
//
// НОЛЬ, А НЕ ХРАПОВИК (в отличие от гарда выброшенного error). Там потолок был
// заморожен потому, что 173 места нельзя починить одним заходом без новой
// аварии. Здесь всё переведено ЭТИМ ЖЕ коммитом, поэтому допустимое число —
// ровно ноль: любой храповик выше нуля означал бы «немного русского можно», а
// это ровно то состояние, из которого мы выходим.
// ============================================================================

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = resolve(HERE, '..')

describe('гард — интерфейс говорит по-английски', () => {
  const { hits, exempt } = scanCyrillicUi(SRC)

  it('в интерфейсе НЕТ кириллицы — ни в строке, ни в тексте JSX', () => {
    const where = hits.map((h: any) => `${h.rel}:${h.line}  ${h.text}`)
    expect(
      where,
      'кириллица в пользовательской строке. Правило владельца 04.08: весь UI — только английский, ' +
      'русский живёт в КОММЕНТАРИЯХ. Если это не текст для человека, а сопоставление с русскими ДАННЫМИ ' +
      '(ответ внешней службы), пометь строку комментарием `ui-english-exempt: <причина>` — причину назвать обязательно.',
    ).toEqual([])
  })

  it('исключений ровно столько, сколько названо — метка не расползается', () => {
    // Три места на день постановки: два сопоставления с русским ответом
    // edge-функции о занятом e-mail и одно такое же в управлении пользователями.
    // Число зафиксировано НАРОЧНО: метка `ui-english-exempt` не должна тихо
    // расползтись по экранам как удобный способ обойти гард.
    expect(exempt.length).toBeLessThanOrEqual(3)
  })

  it('гард отличает комментарий от строки — иначе он запретил бы русские комментарии', () => {
    const src = [
      '// это комментарий, русский тут разрешён',
      'const a = "English only"',
      '/* и блочный комментарий тоже по-русски */',
      'const b = `English too`',
    ].join('\n')
    const stripped = stripComments(src)
    expect(stripped).not.toContain('комментарий')
    expect(stripped).toContain('English only')
    // Номера строк сохраняются — иначе находку невозможно было бы открыть.
    expect(stripped.split('\n')).toHaveLength(4)
  })

  it('гард ловит кириллицу и в строке, и в тексте JSX', () => {
    const src = [
      'const a = "Отметка не сохранена"',
      'const el = <b>Повторить</b>',
    ].join('\n')
    const stripped = stripComments(src)
    expect(/[Ѐ-ӿ]/.test(stripped.split('\n')[0])).toBe(true)
    expect(/[Ѐ-ӿ]/.test(stripped.split('\n')[1])).toBe(true)
  })

  it('дерево читается — гард падает закрыто', () => {
    // «Мы не смогли посмотреть» никогда не должно читаться как «мы посмотрели,
    // и там чисто»: если обход не нашёл ни одного файла, это провал, а не успех.
    const all = scanCyrillicUi(SRC)
    expect(all.hits.length + all.exempt.length).toBeGreaterThanOrEqual(exempt.length)
    expect(exempt.length).toBeGreaterThan(0)
  })
})
