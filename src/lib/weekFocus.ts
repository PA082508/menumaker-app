// src/lib/weekFocus.ts
// ОДИН вычислитель «какая неделя и какой день сейчас перед человеком» (слово
// владельца 08.08). Американская неделя, три разных ответа:
//
//   Пн–Пт  → ТЕКУЩАЯ неделя, ТЕКУЩИЙ день            — обычная работа
//   Сб     → ещё ПРОШЕДШАЯ неделя, день = пятница    — закрытие и подпись директора
//   Вс     → уже СЛЕДУЮЩАЯ Пн–Пт, день = понедельник — новая неделя началась
//
// ПОЧЕМУ ОДНИМ МЕСТОМ. До 08.08 правило жило четырьмя копиями — на кухонной
// двери, у директора, в учительской вкладке и в умолчаниях печати/экспорта, — и
// копии РАЗОШЛИСЬ: суббота на кухне уже показывала следующую неделю, а директор
// в этот самый день подписывал прошедшую. Неделя, которую видит один, обязана
// быть той же, которую видит другой: иначе отметка уходит с `monday_date`, о
// которой второй человек не знает, и расхождение всплывает через месяц — на
// сверке заявки, где его уже не объяснить.
//
// ПОЧЕМУ СУББОТА — ПРОШЕДШАЯ, А ВОСКРЕСЕНЬЕ — СЛЕДУЮЩАЯ. Суббота принадлежит
// закончившейся рабочей неделе: в этот день её закрывают и подписывают, и
// открывать в субботу неделю, которая ещё не началась, значит прятать ровно то,
// ради чего в субботу вообще открывают экран. Воскресенье — уже канун
// понедельника: там смотрят вперёд, а не назад.
//
// ⚠️ ЭТОТ МОДУЛЬ НИЧЕГО НЕ ЗАПИСЫВАЕТ и ничего не запрещает. Он отвечает на
// вопрос «что показать по умолчанию»; выбрать другую неделю руками можно всегда.

import { startOfWeek, addDays } from 'date-fns'

export type WeekDayKey = 'mon' | 'tue' | 'wed' | 'thu' | 'fri'

/** Понедельник недели, которой принадлежит дата (неделя Пн–Вс). */
export const mondayOfWeek = (d: Date): Date => startOfWeek(d, { weekStartsOn: 1 })

export const WEEK_DAYS: WeekDayKey[] = ['mon', 'tue', 'wed', 'thu', 'fri']

export type WeekFocusKind =
  | 'working-day'       // Пн–Пт: текущая неделя, сегодняшний день
  | 'saturday-closing'  // Сб: прошедшая неделя, пятница
  | 'sunday-ahead'      // Вс: следующая неделя, понедельник

export interface WeekFocus {
  /** Понедельник недели, которую показываем (ключ `monday_date` в записях). */
  weekStart: Date
  /** День недели, на котором стоит фокус. */
  day: WeekDayKey
  kind: WeekFocusKind
  /** Строка для человека — почему экран открылся не на сегодняшнем дне. */
  note: string
}

/**
 * Какая неделя и какой день перед человеком ПРЯМО СЕЙЧАС.
 * `now` передаётся аргументом, чтобы правило проверялось чистым тестом, а не
 * ожиданием субботы.
 */
export function weekFocus(now: Date = new Date()): WeekFocus {
  const dow = now.getDay()               // 0=Вс, 1=Пн … 6=Сб
  const monday = mondayOfWeek(now)

  if (dow >= 1 && dow <= 5) {
    return {
      weekStart: monday,
      day: WEEK_DAYS[dow - 1],
      kind: 'working-day',
      note: '',
    }
  }

  if (dow === 6) {
    // Суббота принадлежит закончившейся неделе: `mondayOfWeek` (weekStartsOn:1)
    // отдаёт её понедельник без поправок.
    return {
      weekStart: monday,
      day: 'fri',
      kind: 'saturday-closing',
      note: 'Showing last week — Saturday is when the week is closed and signed.',
    }
  }

  // Воскресенье. `mondayOfWeek` для воскресенья отдаёт понедельник ПРОШЕДШЕЙ
  // недели (неделя кончается воскресеньем), поэтому нужен +7.
  return {
    weekStart: addDays(monday, 7),
    day: 'mon',
    kind: 'sunday-ahead',
    note: 'Showing the week ahead — Monday is next.',
  }
}

/** Только неделя — для экранов, у которых своего дня нет. */
export const focusWeekStart = (now: Date = new Date()): Date => weekFocus(now).weekStart

/** Только день — для плиток и сводок, живущих одним днём. */
export const focusDayKey = (now: Date = new Date()): WeekDayKey => weekFocus(now).day

/** ISO-номер дня фокуса, 1..5. Для мест, где день хранится числом. */
export const focusDowIso = (now: Date = new Date()): number => WEEK_DAYS.indexOf(weekFocus(now).day) + 1
