// Канон 31.07: идентичность не строится на человекочитаемом поле. Ключ строки недели —
// `roster_id`, имя ребёнка — ПОДПИСЬ строки. Ключ по имени породил 115 строк-сирот в июле
// 2026: ростер пишет «Andras Inara», июньский импорт написал «Inara Andras», экран
// индексировал по написанию ростера, строку не находил, и повар отмечал неделю заново.
//
// ⚠️ ПОЧЕМУ ЕСТЬ ЗАПАСНОЙ ПУТЬ ПО ИМЕНИ, А НЕ ПРОСТО roster_id.
// Клиент обязан работать в ДВУХ схемах сразу:
//   • сегодня — ключ в базе ещё по имени (`meal_week_records_unique`);
//   • после 20260731a — частичный ключ по `roster_id`, а строки БЕЗ ребёнка (персонал,
//     92 строки, из них 88 — Ridge «Staff Room») сохраняют СТАРЫЙ ключ по имени.
// Строка без `roster_id` существует и будет существовать законно, поэтому ключ обязан
// иметь честный запасной путь. Префиксы `r:` / `n:` не дают двум пространствам смешаться:
// без них ребёнок с именем, равным чужому uuid, схлопнулся бы с ним.
//
// Утром планшеты сначала пишут в СТАРУЮ схему — этот же ключ там работает без оговорок,
// потому что строки уже несут `roster_id` (бэкфилл 20260730b): в июле строк без ребёнка
// нет ни одной.

export function weekRowKey(
  roster_id: string | null | undefined,
  child_name: string,
): string {
  const rid = (roster_id ?? '').trim()
  return rid ? `r:${rid}` : `n:${child_name}`
}

/**
 * Разложить строки недели по идентичности — С ЧЕСТНЫМ ПРАВИЛОМ НА СТОЛКНОВЕНИИ.
 *
 * Пока ключ в базе старый, две строки одного ребёнка с РАЗНЫМ написанием законны
 * (замер 02.08: таких групп сейчас 0 — схлопнуты, — но старый ключ их не запрещает).
 * Две такие строки дают один `weekRowKey`, и «кто последний, тот и виден» означало бы,
 * что экран показывает одну строку, а тап пишет в другую: галочка вернулась бы после
 * перезагрузки.
 *
 * Поэтому побеждает строка с РОСТЕРНЫМ написанием — ровно та, в которую целится
 * `sync_meal_marks` (клиент шлёт написание ростера). Читаем и пишем одну и ту же строку.
 * Это же правило победителя, что и в схлопывании сирот 20260801c, — не совпадение:
 * разойдись они, чистка и экран называли бы правдой разные строки.
 * После 20260731a столкновений не будет вовсе — частичный ключ их запретит.
 */
export function indexWeekRecords<T extends { roster_id?: string | null; child_name: string }>(
  records: readonly T[],
  roster: ReadonlyArray<{ roster_id?: string | null; child_name: string }>,
): Record<string, T> {
  const rosterName = new Map<string, string>()
  for (const c of roster) rosterName.set(weekRowKey(c.roster_id, c.child_name), c.child_name)

  const out: Record<string, T> = {}
  for (const r of records) {
    const key = weekRowKey(r.roster_id, r.child_name)
    const prev = out[key]
    if (!prev) { out[key] = r; continue }
    const expected = rosterName.get(key)
    if (expected !== undefined && prev.child_name !== expected && r.child_name === expected) out[key] = r
  }
  return out
}
