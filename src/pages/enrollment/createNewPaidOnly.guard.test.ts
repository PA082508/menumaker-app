import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

// ============================================================================
// ГАРД: «Создать нового ребёнка из формы» НЕ ставит доходную категорию.
//
// До 05.08 в этом пути стояло `frp: 'F'` — ребёнок, заведённый из документа,
// сразу становился Free. Определение без бумаги — это деньги, которые нечем
// обосновать на проверке; замер того дня: 52 активных ребёнка с F и без единой
// записи определения. F/R ставится ТОЛЬКО recordDetermination с документной
// датой (карточка / IEA Review).
// ============================================================================

const SRC = fs.readFileSync(
  path.join(__dirname, 'EnrollmentReviewModal.tsx'), 'utf8',
)

describe('create-new-child из формы — категория только Paid', () => {
  it('в патче нового ребёнка стоит frp: \'P\'', () => {
    expect(SRC).toMatch(/frp:\s*'P'/)
  })

  it('доходной константы в этом файле нет вовсе', () => {
    const income = SRC.match(/frp:\s*'(F|R)'/g) ?? []
    expect(income).toEqual([])
  })
})
