-- Гранты на menumaker.published_menus для роли authenticated.
--
-- ПОВОД (замер 04.08). Таблица создана 02.07 вместе с политиками RLS, но БЕЗ
-- единого GRANT: привилегии были только у postgres и service_role. У всех
-- соседних таблиц меню (menu_cycles, menu_items, monthly_menus, holidays) гранты
-- есть — эту забыли, и заметить это было нечем: за месяц её никто не нажимал.
--
-- ПОЧЕМУ ЭТО НЕ ЛОВИЛОСЬ ПОЛИТИКАМИ. RLS и GRANT — два разных замка, и GRANT
-- стоит РАНЬШЕ. Без привилегии PostgREST отвечает «permission denied for table
-- published_menus» и до строк политики не доходит вовсе: сколько ни правь
-- manage_published_menus (а её правили 03.07, добавляя admin), публикация всё
-- равно была невозможна. Первое же нажатие «Publish» дало бы отказ.
--
-- ОБЪЁМ РОВНО ПО ЗАКАЗУ: select + insert, только authenticated.
--   · UPDATE и DELETE НЕ выдаются намеренно — публикация только вперёд:
--     повторная публикация месяца добавляет версию, прежнюю не трогает
--     (DECISIONS 04.08, `ВЕРСИЯ СЧИТАЕТСЯ ПО ЦЕНТРУ`). Роль, которая физически
--     не может переписать снимок, надёжнее правила, которое обещает не переписывать.
--   · anon НЕ получает ничего. Политика чтения read_published_menus сделана
--     широкой ради будущей витрины для сайта/родителей, но маршрут сегодня живёт
--     под ProtectedRoute; открывать анониму таблицу под обещание будущего — это
--     выдать доступ раньше, чем появился тот, кому он нужен.
--
-- Применено к проекту menumaker (trrmyqfpxntmgxnqkikp) 2026-08-04.
