-- ЗАКАЗ ВЛАДЕЛЬЦА 08.08, уточнение к замку: замыкать нужно ТОЛЬКО комнаты,
-- перешедшие на именные отметки через App учителя (сейчас это Red в Wickliffe).
-- Остальные комнаты отмечает ПОВАР — пакетно, по доставке, задним числом внутри
-- дня; замок там отнял бы работающий инструмент раньше, чем дал новый.
--
-- КАНОН: «замок следует за App — замыкается комната, перешедшая на именные
-- отметки». Не «замыкается всё, кроме перечисленных», а наоборот: по умолчанию
-- НИЧЕГО не замкнуто, и каждая комната входит в замок отдельным словом.
--
-- ПОЧЕМУ ФЛАГ НА КЛАССЕ, А НЕ СПИСОК В КОДЕ ИЛИ В НАСТРОЙКАХ ЦЕНТРА:
--   · раскатка идёт ПО КОМНАТАМ, а не по центрам — Red уже на App, соседний
--     Blue ещё нет; носитель обязан иметь ту же зернистость, что и раскатка;
--   · список в коде означал бы правку и выкладку на каждую новую комнату —
--     владелец сказал «расширение словом БЕЗ правки кода»;
--   · признак живёт там же, где `is_roster`, и читается тем же запросом, каким
--     экран и так берёт комнаты: ни одного лишнего похода в базу.
--
-- РАСШИРЕНИЕ — ОДНА СТРОКА, БЕЗ ВЫКЛАДКИ:
--   update menumaker.classrooms set app_marks = true
--    where center_id = <центр> and name = 'Blue';
--
-- ЧЕГО ЭТОТ ФЛАГ НЕ ДЕЛАЕТ: он НЕ прячет комнату, не меняет права и не влияет
-- ни на одну запись отметки. Он отвечает ровно на один вопрос — «замыкать ли
-- здесь закрывшийся приём».
-- ============================================================================

alter table menumaker.classrooms
  add column if not exists app_marks boolean not null default false;

comment on column menumaker.classrooms.app_marks is
  'Комната перешла на именные отметки через App учителя. true → закрывшийся приём '
  'замыкается у учителя (см. specs/2026-08-08-meal-mark-lock.md). Расширяется '
  'словом владельца одной строкой update, без правки кода.';

-- Пилот на 08.08 — Red в Wickliffe (Ridge). Ровно одна комната: на App сегодня
-- работает только она.
update menumaker.classrooms c
   set app_marks = true
  from menumaker.centers ce
 where ce.id = c.center_id
   and ce.slug = 'ridge'
   and c.name = 'Red';
