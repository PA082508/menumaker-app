-- Слово владельца 08.08. Ridge · Alpha · Pearl — рабочие клички, слова стройки;
-- наружу центр называется по городу, и «наружу» включает всё, что берёт имя из
-- `centers.name`: сервер App учителя (safepass_identify_by_pin), печатные
-- конвейеры, выгрузки, письма.
--
-- ЗАМЕР ПЕРЕД ПРАВКОЙ (08.08): ни одна функция и ни одно представление базы на
-- ТЕКСТ имени центра не завязаны — переименование ничего не рвёт. Ключом везде
-- служит `slug`, и он НЕ трогается.
--
-- Перевод, живущий в коде (`centerOfficialName`), после этого схлопывается сам:
-- он отдаёт `name` как есть, если кличка ему незнакома. Оставлен страховкой.
--
-- ФОРВАРД-ОНЛИ: применено как акт по слову, файл кладётся следом за фактом.
-- READ-BACK (после применения): кличек в именах центров — 0; имя, которое видит
-- App учителя, — «Play Academy Wickliffe».
-- ============================================================================

update menumaker.centers set name = 'Play Academy Wickliffe'     where slug = 'ridge';
update menumaker.centers set name = 'Play Academy Parma Heights' where slug = 'pearl';
